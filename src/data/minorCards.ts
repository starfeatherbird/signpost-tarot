import type { Suit, TarotCard } from '../domain/types';

/**
 * 마이너 아르카나 56장. 수트별 14장(에이스~10, 페이지·나이트·퀸·킹).
 * id 는 그림 파일명 규칙(ACE OF WANDS.png → ace-of-wands)과 같습니다.
 * number 는 덱 안 고유 번호(22~77)이며 화면에는 "완드 3" 처럼 수트와 순서로 표시합니다.
 */

export const SUIT_KO: Record<Suit, string> = { wands: '완드', cups: '컵', swords: '소드', pentacles: '펜타클' };
const SUIT_EN: Record<Suit, string> = { wands: 'Wands', cups: 'Cups', swords: 'Swords', pentacles: 'Pentacles' };
const SUIT_SYMBOL: Record<Suit, string> = { wands: '⚚', cups: '☖', swords: '†', pentacles: '◎' };

const RANK_EN = ['', 'Ace', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Page', 'Knight', 'Queen', 'King'];
export const RANK_KO = ['', '에이스', '2', '3', '4', '5', '6', '7', '8', '9', '10', '페이지', '나이트', '퀸', '킹'];

/** 카드 한 장의 내용 (수트·순서 외) */
interface Body {
  keywords: [string, string, string];
  reversedKeywords: [string, string, string];
  essence: string;
  reversedEssence: string;
  core: string;
  blindspot: string;
  next: string;
  actions: [string, string];
}

function build(suit: Suit, bodies: Body[], startNumber: number): TarotCard[] {
  return bodies.map((b, i) => {
    const rank = i + 1;
    const rankEn = RANK_EN[rank];
    return {
      id: `${rankEn.toLowerCase()}-of-${suit}`,
      number: startNumber + i,
      arcana: 'minor',
      suit,
      rank,
      nameKo: `${SUIT_KO[suit]} ${RANK_KO[rank]}`,
      nameEn: `${rankEn} of ${SUIT_EN[suit]}`,
      symbol: SUIT_SYMBOL[suit],
      keywords: [...b.keywords],
      reversedKeywords: [...b.reversedKeywords],
      essence: b.essence,
      reversedEssence: b.reversedEssence,
      perspectives: { core: b.core, blindspot: b.blindspot, next: b.next },
      actions: [...b.actions],
    };
  });
}

